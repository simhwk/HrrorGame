// =====================================================================
// [스크립트 역할] 표식(갈림길 확인 수단) 단계 정의
// 루프 진행도에 따라 플레이어가 갈림길을 확인하는 방식이 달라짐을 나타내는 열거형이다.
// =====================================================================
namespace CaveGame // 이 프로젝트의 스크립트들을 묶는 이름표(다른 에셋의 동일 이름 클래스와 충돌 방지)
{
    /// <summary>
    /// 표식 3단계 — Tape(1~3루프, 시각 확인) / Guideline(4~6루프, 촉각 확인) / Bloodstain(7루프, 확인 수단 없음).
    /// </summary>
    public enum MarkerStage // enum: 정해진 몇 개의 값 중 하나만 가질 수 있는 타입(여기선 3가지 단계)
    {
        Tape = 1,       // 테이프 표식: 눈으로 바로 확인 가능. 정수값 1을 명시적으로 부여(저장/비교 시 명확하게)
        Guideline = 2,  // 가이드라인 표식: 손으로 만져서(Interact Hold) 확인해야 함. 정수값 2
        Bloodstain = 3, // 핏자국 표식: 확인 수단이 없음(가장 위험한 단계). 정수값 3
    }
}
